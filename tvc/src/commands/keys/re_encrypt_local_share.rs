/// Re-encrypt a share with an ephemeral key.
#[derive(Debug, ClapArgs)]
#[command(about, long_about = None)]
pub struct Args {
    /// Path to the quorum key metadata file, which is generated by the `generate-local-quorum-key` command
    /// and includes the share to re-encrypt.
    /// The relevant share is assumed to be encrypted by the operator key.
    #[arg(long, value_name = "PATH", env = "TVC_QUORUM_KEY_METADATA")]
    pub quorum_key_metadata: PathBuf,

    /// Provision bundle from a deployment.
    /// This should match the output format of `tvc deploy provisioning-details`.
    #[arg(long, value_name = "PATH", env = "TVC_PROVISION_BUNDLE")]
    pub provision_bundle: PathBuf,

    /// Hex-encoded 32-byte master seed for the operator key.
    /// If no seed flag is provided, uses the operator key from the logged-in org config.
    #[arg(
        long,
        value_name = "HEX_SEED",
        env = "TVC_OPERATOR_SEED",
        help_heading = "Operator seed (pick one)"
    )]
    pub operator_seed: Option<HexSeed>,

    /// Path to a file containing the hex-encoded master seed for the operator key.
    #[arg(
        long,
        value_name = "PATH",
        env = "TVC_OPERATOR_SEED_PATH",
        help_heading = "Operator seed (pick one)"
    )]
    pub operator_seed_path: Option<PathBuf>,

    /// Serial (hex) of the YubiKey operator to decrypt with, when the
    /// organization registers several. Unused for other operator kinds.
    #[arg(long, value_name = "SERIAL")]
    pub serial: Option<YubiKeySerial>,

    /// Never use for sensitive applications! Skip attestation, PCR, and manifest approval verification.
    #[arg(long, env = "TVC_DANGEROUS_SKIP_VERIFICATION")]
    pub dangerous_skip_verification: bool,

    /// DANGEROUS: skip interactive prompts for approving each aspect of the manifest
    /// before the share is re-encrypted to it.
    #[arg(long, env = "TVC_DANGEROUS_SKIP_INTERACTIVE")]
    dangerous_skip_interactive: bool,

    /// Path to the app config whose `manifestSetParams` is trusted in place of the
    /// interactive manifest review: the manifest set must match it exactly and its
    /// approvals must meet the threshold.
    #[arg(
        long,
        value_name = "PATH",
        env = "TVC_TRUSTED_APP_CONFIG",
        conflicts_with = "dangerous_skip_interactive"
    )]
    trusted_app_config: Option<PathBuf>,

    /// Output path for the re-encrypted share output (share ciphertext + manifest approval).
    #[arg(long, value_name = "PATH", env = "TVC_RE_ENCRYPTED_OUT")]
    pub re_encrypted_out: Option<PathBuf>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub(crate) struct ReEncryptedShareOutput {
    pub(crate) deployment_id: String,
    pub(crate) ephemeral_public_key_hex: String,
    pub(crate) re_encrypted_share: String,
    pub(crate) share_approval: Approval,
}

/// Wide terminal outcome covering both output branches: the share payload
/// inline (no `--re-encrypted-out`) or the path it was written to.
#[derive(Default, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ReEncryptedShareGenerated {
    /// Present when the share is returned inline (no `--re-encrypted-out`).
    #[serde(flatten)]
    share: Option<ReEncryptedShareOutput>,
    /// Present when the share was written to a file via `--re-encrypted-out`.
    #[serde(skip_serializing_if = "Option::is_none")]
    written_to: Option<String>,
}

impl Display for ReEncryptedShareGenerated {
    fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
        match &self.share {
            // Preserve the previous human behavior: pretty-printed share JSON.
            Some(share) => {
                let json = serde_json::to_string_pretty(share)
                    .expect("serializing re-encrypted share should not fail");
                f.write_str(&json)
            }
            // File branch: the "Re-encrypted share written to: ..." narration
            // prints inline on stderr; the outcome is machine-only, so human
            // mode prints nothing here.
            None => Ok(()),
        }
    }
}

/// Run the re-encrypt-local-share command.
pub async fn run(ctx: &mut StdCtx, args: Args, config: Config) -> anyhow::Result<Outcome> {
    let can_prompt = !ctx.is_non_interactive() && stdin_can_prompt();
    let operator_seed_source =
        LocalOperatorSeedSource::from_args(args.operator_seed, args.operator_seed_path)?;

    let manifest_review = match (args.trusted_app_config, args.dangerous_skip_interactive) {
        (Some(path), _) => {
            let app_config: AppConfig = read_json_file(&path, "trusted app config").await?;
            ManifestReview::TrustedAppConfig(
                TrustedManifestSet::try_from(app_config)
                    .with_context(|| format!("trusted app config {}", path.display()))?,
            )
        }
        (None, true) => ManifestReview::DangerousSkip,
        (None, false) if can_prompt => ManifestReview::Interactive,
        (None, false) => {
            return Err(prompts::error_required_in_non_interactive(
                "--trusted-app-config or --dangerous-skip-interactive",
            ));
        }
    };

    if args.dangerous_skip_verification {
        shell_eprintln!(
            ctx,
            "WARNING: Skipping attestation, PCR, and manifest approval verification! This is dangerous and should not be used for sensitive applications."
        )?;
    }

    let selected_yubikey = config
        .active_org_config()
        .filter(|(_, org)| {
            operator_seed_source.is_none() && org.default_operator_kind == OperatorKind::Yubikey
        })
        .map(|(alias, org)| {
            let selected = match args.serial {
                Some(serial) => Ok(org.select_yubikey_operator(Some(serial))?),
                None => match org.select_yubikey_operator(None) {
                    Ok(selected) => Ok(selected),
                    Err(SelectYubiKeyOperatorError::MultipleYubiKeyOperators { .. })
                        if can_prompt =>
                    {
                        struct Choice<'a>(&'a OperatorRecord, &'a YubiKeyOperatorRecord);

                        impl Display for Choice<'_> {
                            fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
                                write!(f, "{} (serial {})", self.0.name, self.1.serial)
                            }
                        }

                        let choices = org
                            .yubikey_operators()
                            .map(|(operator, yubikey)| Choice(operator, yubikey))
                            .collect();
                        let Choice(operator, yubikey) =
                            prompts::select("Select YubiKey operator", choices)?;

                        Ok((operator, yubikey))
                    }
                    Err(error @ SelectYubiKeyOperatorError::MultipleYubiKeyOperators { .. }) => {
                        Err(anyhow::Error::new(error)
                            .context(MissingRequiredInput::new("--serial")))
                    }
                    Err(error) => Err(error.into()),
                },
            }
            .with_context(|| format!("org '{alias}'"))?;

            if !can_prompt {
                anyhow::bail!(
                    "a YubiKey operator needs its PIN typed at an interactive prompt; \
                     the PIN is never read from config or the environment"
                );
            }

            let pin = Pin::from(prompts::password(
                "YubiKey PIV PIN (touch the device each time it blinks)",
            )?);

            Ok(SelectedYubiKey::new(selected.1.serial, pin))
        })
        .transpose()?;

    // Backend selection and any terminal input settle before the input files
    // are read; device access waits until the files are valid.
    let pair_source = config.select_operator_pair_source(operator_seed_source, selected_yubikey)?;

    let quorum_key_metadata: QuorumKeyMetadata =
        read_json_file(&args.quorum_key_metadata, "quorum key metadata file").await?;
    let provision_bundle: ProvisionBundle =
        read_json_file(&args.provision_bundle, "provision bundle").await?;
    ensure_quorum_key_matches_manifest(&quorum_key_metadata, &provision_bundle)?;
    let ephemeral_public_key =
        provision_bundle.ephemeral_public_key(args.dangerous_skip_verification)?;

    // The bundle's own manifest set approvals and attestation only prove the
    // enclave runs the manifest it carries; the share holder still has to
    // establish that manifest is one they trust before handing over a share.
    let provision_bundle = match manifest_review {
        ManifestReview::Interactive => {
            interactive_approve(
                ctx,
                &provision_bundle.manifest_envelope().clone().manifest(),
            )?;
            ReviewedProvisionBundle(provision_bundle)
        }
        ManifestReview::TrustedAppConfig(trusted) => trusted.trust(provision_bundle)?,
        ManifestReview::DangerousSkip => ReviewedProvisionBundle(provision_bundle),
    };

    let operator_pair = pair_source.resolve(&config, yubikey::open).await?;

    let output = build_re_encrypted_share_output(
        &quorum_key_metadata,
        &provision_bundle,
        &ephemeral_public_key,
        operator_pair.as_ref(),
    )
    .await?;

    write_output(ctx, args.re_encrypted_out.as_deref(), output).await
}

/// How the share holder establishes trust in the bundle's manifest.
enum ManifestReview {
    Interactive,
    TrustedAppConfig(TrustedManifestSet),
    DangerousSkip,
}

/// A provision bundle whose manifest passed the share holder's
/// [`ManifestReview`]; only that review constructs it.
#[cfg_attr(test, derive(Debug))]
struct ReviewedProvisionBundle(ProvisionBundle);

/// The manifest set an app config declares, as the keys and threshold a
/// manifest must carry to be trusted.
#[cfg_attr(test, derive(Debug))]
struct TrustedManifestSet {
    threshold: NonZeroU32,
    members: BTreeSet<Vec<u8>>,
}

impl TryFrom<AppConfig> for TrustedManifestSet {
    type Error = anyhow::Error;

    fn try_from(app_config: AppConfig) -> anyhow::Result<Self> {
        let Some(OperatorSetParams {
            threshold,
            new_operators,
            existing_operator_ids,
            name: _,
        }) = app_config.manifest_set_params
        else {
            bail!("manifestSetParams is required to trust the manifest set offline");
        };
        ensure!(
            existing_operator_ids.is_empty(),
            "manifestSetParams.existingOperatorIds cannot be checked offline; list those operators' public keys in newOperators"
        );
        let threshold =
            NonZeroU32::new(threshold).context("manifestSetParams.threshold must be at least 1")?;
        let members: BTreeSet<Vec<u8>> = new_operators
            .into_iter()
            .map(|operator| {
                hex::decode(&operator.public_key).with_context(|| {
                    format!(
                        "invalid public key for manifest set operator '{}'",
                        operator.name
                    )
                })
            })
            .collect::<anyhow::Result<_>>()?;
        ensure!(
            threshold.get() as usize <= members.len(),
            "manifestSetParams.threshold ({threshold}) exceeds its {} distinct newOperators",
            members.len()
        );

        Ok(Self { threshold, members })
    }
}

impl TrustedManifestSet {
    fn trust(&self, provision_bundle: ProvisionBundle) -> anyhow::Result<ReviewedProvisionBundle> {
        let manifest_envelope = provision_bundle.manifest_envelope();
        let manifest_set = manifest_envelope.manifest_set();
        let members: BTreeSet<&[u8]> = manifest_set
            .members
            .iter()
            .map(|member| member.pub_key.as_slice())
            .collect();
        ensure!(
            manifest_set.threshold == self.threshold.get()
                && members
                    .into_iter()
                    .eq(self.members.iter().map(Vec::as_slice)),
            "provision bundle manifest set does not match the trusted app config manifest set"
        );

        // Trusting the set only means something if enough of its members
        // approved this manifest, which `--dangerous-skip-verification` would
        // otherwise leave unchecked.
        manifest_envelope
            .check_approvals()
            .context("failed to verify manifest approvals")?;

        Ok(ReviewedProvisionBundle(provision_bundle))
    }
}

async fn build_re_encrypted_share_output(
    quorum_key_metadata: &QuorumKeyMetadata,
    ReviewedProvisionBundle(provision_bundle): &ReviewedProvisionBundle,
    ephemeral_public_key: &P256Public,
    // Re-encryption decrypts the share, so a [`Signer`] alone is not enough;
    // the operator's key material must be able to decrypt.
    operator_pair: &dyn Pair,
) -> anyhow::Result<ReEncryptedShareOutput> {
    let operator_public_key = operator_pair.public_key();
    let encrypted_share = quorum_key_metadata.encrypted_share_for_operator(&operator_public_key)?;
    let member = find_share_set_member(provision_bundle.manifest_envelope(), &operator_public_key)?;

    let re_encrypted_share = {
        let plaintext_share = operator_pair
            .decrypt(&encrypted_share)
            .await
            .context("failed to decrypt share with operator key")?;

        ephemeral_public_key
            .encrypt(plaintext_share.as_slice())
            .map_err(|err| anyhow!("failed to encrypt share to ephemeral key: {err:?}"))?
    };

    let signature = operator_pair
        .sign(&provision_bundle.manifest_envelope().manifest_hash())
        .await
        .context("failed to sign share approval with operator key")?;
    let share_approval = Approval { signature, member };

    Ok(ReEncryptedShareOutput {
        deployment_id: provision_bundle.deployment_id().to_string(),
        ephemeral_public_key_hex: hex::encode(ephemeral_public_key.to_bytes()),
        re_encrypted_share: hex::encode(re_encrypted_share),
        share_approval,
    })
}

fn ensure_quorum_key_matches_manifest(
    quorum_key_metadata: &QuorumKeyMetadata,
    provision_bundle: &ProvisionBundle,
) -> anyhow::Result<()> {
    let metadata_quorum_key = quorum_key_metadata.quorum_key_public_bytes()?;
    let manifest = provision_bundle.manifest_envelope().clone().manifest();
    let manifest_quorum_key = &manifest.namespace().quorum_key;

    if metadata_quorum_key.as_slice() != manifest_quorum_key.as_slice() {
        anyhow::bail!(
            "quorum key metadata quorumKeyPublic ({}) does not match provision bundle manifest quorumKey ({})",
            hex::encode(metadata_quorum_key),
            hex::encode(manifest_quorum_key),
        );
    }

    Ok(())
}

fn find_share_set_member(
    manifest_envelope: &VersionedManifestEnvelope,
    operator_public_key: &[u8],
) -> anyhow::Result<QuorumMember> {
    manifest_envelope
        .clone()
        .manifest()
        .share_set()
        .members
        .iter()
        .find(|member| member.pub_key == operator_public_key)
        .cloned()
        .ok_or_else(|| {
            anyhow!(
                "operator ({}) not part of share set",
                hex::encode(operator_public_key)
            )
        })
}

async fn write_output(
    ctx: &mut StdCtx,
    path: Option<&Path>,
    output: ReEncryptedShareOutput,
) -> anyhow::Result<Outcome> {
    let generated = if let Some(path) = path {
        let contents = serde_json::to_string_pretty(&output)
            .context("failed to serialize re-encrypted share")?;
        write_file(path, &contents).await?;
        shell_eprintln!(ctx, "Re-encrypted share written to: {}", path.display())?;
        ReEncryptedShareGenerated {
            share: None,
            written_to: Some(path.display().to_string()),
        }
    } else {
        ReEncryptedShareGenerated {
            share: Some(output),
            written_to: None,
        }
    };

    Ok(Outcome::ReEncryptedShareGenerated(generated))
}

